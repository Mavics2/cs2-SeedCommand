-- ============================================================
-- Triggers — auto-apply best_seed + Factory New wear when paint changes
-- ============================================================
DROP TRIGGER IF EXISTS best_seed_before_update;
DROP TRIGGER IF EXISTS best_seed_before_insert;

DELIMITER //

CREATE TRIGGER best_seed_before_update BEFORE UPDATE ON wp_player_skins
FOR EACH ROW
BEGIN
    DECLARE v_best INT;
    IF NEW.weapon_paint_id <> OLD.weapon_paint_id THEN
        SET NEW.weapon_wear = 0.000001;
        SELECT best_seed INTO v_best FROM best_seeds
        WHERE weapon_defindex = NEW.weapon_defindex
          AND weapon_paint_id = NEW.weapon_paint_id LIMIT 1;
        IF v_best IS NOT NULL THEN SET NEW.weapon_seed = v_best; END IF;
    END IF;
END //

CREATE TRIGGER best_seed_before_insert BEFORE INSERT ON wp_player_skins
FOR EACH ROW
BEGIN
    DECLARE v_best INT;
    SET NEW.weapon_wear = 0.000001;
    SELECT best_seed INTO v_best FROM best_seeds
    WHERE weapon_defindex = NEW.weapon_defindex
      AND weapon_paint_id = NEW.weapon_paint_id LIMIT 1;
